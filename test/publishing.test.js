import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { once } from 'node:events';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { test } from 'node:test';
import { createApp } from '../src/app.js';
import { createToken, tokenHash } from '../src/auth.js';
import { openStore } from '../src/store.js';
import { mediaStorage } from '../src/media.js';
import { ayrshare, publishingKeys } from '../src/partner.js';
import { publishService } from '../src/publishing.js';

test('owner links a profile, publishes independently, checks a pending result and retries only the failed target', async (t) => {
  const dir = mkdtempSync(join(tmpdir(),'hub-publish-'));
  const path = join(dir,'db.sqlite');
  const store = openStore(path);
  const db = new DatabaseSync(path);
  const media = mediaStorage(join(dir,'media'),store);
  media.clean();
  const keys = publishingKeys(randomBytes(32).toString('base64'));
  const remote = [];
  let failed = true;
  let linked = false;
  const adapter = ayrshare('fixture-key', async (url, request) => {
    const body = request.body && JSON.parse(request.body);
    const api = new URL(url).pathname;
    const ok = (value) => Response.json(value);
    if (api === '/api/profiles') return ok({ profileKey:'test-profile' });
    assert.equal(request.headers['Profile-Key'],'test-profile');
    if (api === '/api/profiles/link-sessions') return ok({ url:'https://profile.ayrshare.com/?session=test',expiresAt:new Date(Date.now()+300000).toISOString() });
    if (api === '/api/user') return ok({ activeSocialAccounts:linked ? ['youtube','facebook','instagram','tiktok'] : [] });
    if (api === '/api/profiles/social') { linked = false; return ok({status:'success'}); }
    if (api === '/api/post') {
      remote.push(body);
      const [platform] = body.platforms;
      const id = 'job-' + platform;
      if (platform === 'facebook' && failed) return Response.json({ status:'error', posts:[{status:'error',errors:[{message:'Page permission expired.'}]}] },{status:400});
      const socialId = platform === 'youtube' || platform === 'tiktok' ? 'pending' : 'social-' + platform;
      return ok({status:'success',posts:[{id,status:'success',postIds:[{platform,id:socialId,status:'success'}]}]});
    }
    if (api === '/api/post/job-youtube') return ok({id:'job-youtube',postIds:[{platform:'youtube',id:'confirmed',status:'success'}]});
    throw new Error('Unexpected provider request ' + api);
  });
  const service = publishService(store,{partner:adapter, keys, enabled:true, mode:'draft', publicOrigin:'https://media.example'});
  const origin = 'http://localhost:3000';
  const server = createApp({store,media,origin,publishing:service});
  server.listen(0,'127.0.0.1');
  await once(server,'listening');
  t.after(async () => {
    await new Promise((resolve) => server.close(resolve));
    db.close(); store.close(); rmSync(dir,{recursive:true,force:true});
  });
  const base = 'http://127.0.0.1:' + server.address().port;
  store.createOwner({name:'Owner',email:'owner@example.com',passwordHash:'fixture'});
  const token = createToken();
  store.createSession(tokenHash(token));
  const cookie = 'upload_hub=' + token;
  const post = (route,values) => fetch(base+route,{method:'POST',headers:{ Origin:origin,Cookie:cookie },body:new URLSearchParams(values),redirect:'manual'});
  const get = (route) => fetch(base+route,{headers:{Cookie:cookie},redirect:'manual'});
  const owner = store.getOwner();
  const folder = store.getChannel(owner.id,store.createChannel(owner.id,'Test channel'));
  const accountRoute = '/channels/'+folder.id+'/accounts';
  assert.equal((await fetch(base+accountRoute,{redirect:'manual'})).status,303);
  const connect = await post(accountRoute,{intent:'connect',platform:'Instagram'});
  assert.equal(connect.headers.get('location'),'https://profile.ayrshare.com/?session=test');
  assert.notEqual(store.publishing.profile(folder.id).secret,'test-profile');
  store.publishing.linkAttempt(folder.id,'Instagram',Date.now()-1000);
  assert.match(await (await get(accountRoute)).text(),/Link expired/);
  linked = true;
  assert.match(await (await get(accountRoute)).text(),/Connected/);
  await post(accountRoute,{platform:'Instagram',intent:'disconnect'});
  assert.match(await (await get(accountRoute)).text(),/Not connected/);
  linked = true;
  await get(accountRoute);
  assert.equal((await get('/channels/00000000-0000-0000-0000-000000000000/accounts')).status,404);
  const id = store.createUpload(folder.id,'clip.mp4',5);
  writeFileSync(join(dir,'media',id),'video');
  store.finalizeUpload(owner.id,store.getUpload(folder.id,id),{duration:60,width:1080,height:1920,hash:'fixture'},false);
  const route = '/channels/'+folder.id+'/videos/'+id;
  const selected = ['YouTube','Facebook','Instagram','TikTok'];
  const publish = (selectedNames) => post(route+'/publish', [
    ['revision',String(store.getVideo(folder.id,id).updated_at)],
    ...selectedNames.flatMap((name)=>[['platform',name],['account-'+name,name.toLowerCase()]])
  ]);
  const options = {kids:'no',consent:'on',...Object.fromEntries(selected.map((name)=>[name,'on']))};
  await post(route+'/platforms',options);
  db.prepare("UPDATE publish_rules SET daily_limit=1 WHERE platform='Facebook'").run();
  db.prepare("INSERT INTO quota_reservations VALUES('previous',?,'Facebook',?)").run(folder.id,Date.now());
  assert.match(await (await publish(['Facebook'])).text(),/limit reached/);
  db.prepare("DELETE FROM quota_reservations WHERE target='previous'").run();
  await post(route+'/platforms',{...options,'Instagram-caption':'x'.repeat(2201)});
  assert.match(await (await publish(['Instagram'])).text(),/exceeds/);
  await post(route+'/platforms',options);
  db.prepare('UPDATE videos SET width=10 WHERE id=?').run(id);
  assert.match(await (await publish(['TikTok'])).text(),/aspect ratio/);
  db.prepare('UPDATE videos SET width=1080 WHERE id=?').run(id);
  assert.equal(store.publishing.targets(id).length,0);
  assert.equal((await publish(selected)).headers.get('location'),'/activity');
  await publish(selected);
  await service.tick();
  const states = () => Object.fromEntries(store.publishing.targets(id).map((row)=>[row.platform,row.state]));
  assert.deepEqual(states(),{YouTube:'Publishing',Facebook:'Failed',Instagram:'Published',TikTok:'Needs manual action'});
  assert.equal(remote.length,4);
  const signed = new URL(remote[0].mediaUrls[0]);
  assert.equal(await (await fetch(base+signed.pathname+signed.search)).text(),'video');
  assert.equal((await fetch(base+signed.pathname+'?sig=wrong')).status,404);
  db.prepare("UPDATE publications SET due=0 WHERE platform='YouTube'").run();
  await service.tick();
  assert.equal(states().YouTube,'Published');
  assert.match(await (await get('/activity?state=Failed')).text(),/Page permission expired/);
  const target = store.publishing.targets(id).find((row)=>row.platform==='Facebook');
  failed = false;
  await post('/activity/retry',{id:target.id});
  await service.tick();
  assert.equal(states().Facebook,'Published');
  assert.equal(remote.length,5);
  assert.match(await (await get(route+'/review')).text(),/Published/);
});
